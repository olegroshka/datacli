"""The canonical register row, the per-market history store and the refresh rule.

Every market's register is published as **one file holding the whole history**
(the FCA's historic disclosures, the AMF's export since 2012), regenerated by
the regulator. The store therefore keeps one ``history.parquet`` per market,
replaced atomically when the published file changes, with the previous
version kept one generation back and a ``state.json`` sidecar (file date,
rows, sha256 of the raw bytes, fetch time, source). A new file with fewer
rows than the stored one is refused: a history must not shrink.

Canonical columns (one row per published position change):

- ``market``: ``uk`` (FCA), ``fr`` (AMF), ``nl`` (AFM), ``se`` (Finansinspektionen),
  ``no`` (Finanstilsynet), ``ie`` (Central Bank of Ireland), ``de`` (Bundesanzeiger);
- ``holder``, ``holder_lei`` (the AMF publishes the LEI, the FCA does not);
- ``issuer``, ``isin``;
- ``net_short_pct``: percent of the issuer's share capital, as published
  (``0.0`` where the regulator records a position falling below the
  publication threshold);
- ``position_date``: the date the position was held;
- ``published_from``: the first day the public could see the row (the AMF
  publishes it; the FCA discloses by 15:30 on the next trading day, so the
  next weekday is used, UK holidays ignored and recorded as a limit);
- ``published_to``: the AMF's end of publication, missing for the FCA and
  for rows still current;
- ``file_date``: the date of the published file the row came from.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

import pandas as pd
import pyarrow as pa

import _atomic  # type: ignore[import-not-found]

MARKETS: tuple[str, ...] = ("uk", "fr", "nl", "se", "no", "ie", "de")
#: Markets whose register is still published per holder (the UK's froze in July 2026).
LIVE_MARKETS: tuple[str, ...] = ("fr", "nl", "se", "no", "ie", "de")
PUBLICATION_THRESHOLD_PCT = 0.5

SCHEMA = pa.schema(
    [
        ("market", pa.string()),
        ("holder", pa.string()),
        ("holder_lei", pa.string()),
        ("issuer", pa.string()),
        ("isin", pa.string()),
        ("net_short_pct", pa.float64()),
        ("position_date", pa.date32()),
        ("published_from", pa.date32()),
        ("published_to", pa.date32()),
        ("file_date", pa.date32()),
    ]
)
COLUMNS: tuple[str, ...] = tuple(SCHEMA.names)


class RegisterError(Exception):
    """A transport or format problem; the message is user-facing."""


@dataclass(frozen=True)
class Parsed:
    """One parsed published file: its date and the canonical rows."""

    file_date: dt.date
    rows: pd.DataFrame
    #: Rows the parser left out (file trailers, rows without a key); reported, not stored.
    dropped: int = 0


def next_weekday(day: dt.date) -> dt.date:
    """The next Monday to Friday after ``day``."""
    out = day + dt.timedelta(days=1)
    while out.weekday() >= 5:
        out += dt.timedelta(days=1)
    return out


def canonical(frame: pd.DataFrame, *, market: str, file_date: dt.date) -> pd.DataFrame:
    """Order, type and sort a frame that already carries the canonical columns (``market``/``file_date`` filled here)."""
    out = frame.copy()
    out["market"] = market
    out["file_date"] = file_date
    for column in ("position_date", "published_from", "published_to"):
        parsed = pd.to_datetime(out[column], errors="coerce")
        out[column] = parsed.dt.date.astype(object).where(parsed.notna(), None)
    out["net_short_pct"] = pd.to_numeric(out["net_short_pct"], errors="coerce")
    for column in ("holder", "holder_lei", "issuer", "isin"):
        out[column] = out[column].astype("string").str.strip().replace({"": None}).astype(object).where(out[column].notna(), None)
    bad = out["net_short_pct"].isna() | out["position_date"].isna() | out["isin"].isna() | out["holder"].isna()
    if bad.any():
        raise RegisterError(f"{int(bad.sum())} rows without a holder, an ISIN, a position date or a percentage")
    out = out[list(COLUMNS)].sort_values(["holder", "isin", "position_date"], kind="stable").reset_index(drop=True)
    return out


def to_table(frame: pd.DataFrame) -> pa.Table:
    return pa.Table.from_pandas(frame[list(COLUMNS)], schema=SCHEMA, preserve_index=False)


